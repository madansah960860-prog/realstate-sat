  <section class="section" id="how-we-are-compensated">
    <div class="wrap wrap--narrow">
      <div class="reveal">
        <p class="label">Plain English</p>
        <h2>How we are compensated</h2>
        <p>Real estate compensation is negotiable and is not set by law. Here is every way this business earns money.</p>

        <h3>Commission on representation</h3>
        <p>When we represent a buyer, our fee is agreed in writing with that buyer before we tour a property. The amount and the payer are both negotiable. Depending on what is negotiated, the fee may be paid by the buyer directly, offered by the seller, offered by the listing brokerage, or shared between them. There is no standard rate, and any rate you see quoted as standard is not.</p>
        <p>When we represent a seller, our fee is agreed in writing in the listing agreement and is paid from the seller's proceeds at closing.</p>

        <h3>Referral fees from partner brokerages</h3>
        <p>We are licensed in Florida, Texas and Arizona. If you are buying somewhere we are not licensed, we introduce you to a brokerage that is, and we receive a referral fee from that brokerage out of its commission. That fee does not increase what you pay. We tell you the arrangement exists and the percentage before you speak to the receiving agent.</p>

        <h3>Fee-based concierge services</h3>
        <p>Relocation coordination and downsizing support are billed as flat fees, published on the service pages. They are optional, they are separate from any commission, and you can decline them and still be represented by us.</p>

        <h3>Paid community placements</h3>
        <p>Developers and homeowner associations can pay to have a community featured on this site. Every paid placement is labelled as advertising on the card, on the community page, and in the market reports. Paying for placement does not change what the research says about a community, and we have declined placements we could not write honestly about.</p>

        <h3>Partner referral relationships</h3>
        <p>We maintain a short list of moving, storage and estate-sale companies. Some of them pay us a referral fee. Where that is the case, we disclose it at the point of the recommendation, in the same sentence as the recommendation, not in a footnote.</p>

        <h3>What we do not do</h3>
        <p>We do not sell your contact information, we do not run a lead-generation business, and we do not accept payment to rank one property above another in search results on this site.</p>
        <p><a class="textlink" href="licensing-disclosures.html">Full licensing and brokerage disclosures</a></p>
